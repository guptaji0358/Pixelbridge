/// Format-information indicator bits for L, M, Q, H.
pub const ECC_FORMAT_BITS: [u32; 4] = [1, 0, 3, 2];

/// Number of data+ECC bits that fit in a symbol of the given version,
/// after all function patterns are excluded. Includes remainder bits.
pub fn num_raw_data_modules(ver: usize) -> usize {
    let mut result = (16 * ver + 128) * ver + 64;
    if ver >= 2 {
        let num_align = ver / 7 + 2;
        result -= (25 * num_align - 10) * num_align - 55;
        if ver >= 7 {
            result -= 36;
        }
    }
    result
}

/// Number of 8-bit data codewords (excluding ECC) for a version / ECC level.
pub fn num_data_codewords(ver: usize, ecl: usize) -> usize {
    num_raw_data_modules(ver) / 8
        - ECC_CODEWORDS_PER_BLOCK[ecl][ver] as usize * NUM_ERROR_CORRECTION_BLOCKS[ecl][ver] as usize
}
